const MUTATION_MARKER_KEY = "mutationMayInvalidateRecordedFeatureFlags";

// Mirrors every synthetic session id suffix format; add new ones here too.
const SUFFIX_DESCRIPTIONS: ReadonlyArray<{
  pattern: RegExp;
  describe: (match: RegExpMatchArray) => string;
}> = [
  {
    pattern: /_p(\d{13})(?=_|$)/g,
    describe: (match) =>
      `patched (_p, ${new Date(Number(match[1])).toISOString()}): Meticulous repaired or generated some of its recorded responses or element selectors, e.g. for requests the original recording never made`,
  },
  {
    pattern: /_sl(\d+)(?=_|$)/g,
    describe: (match) =>
      `sliced (_sl${match[1]}): one part of a longer recording`,
  },
  {
    pattern: /_mut[0-9a-f]{8}(?=_|$)/g,
    describe: () =>
      "mutated (_mut): Meticulous changed this copy of the recording, e.g. its recorded data or user flow, to cover more of the app",
  },
  {
    pattern: /_ff[0-9a-f]{8}(?=_|$)/g,
    describe: () =>
      "feature-flag override (_ff): Meticulous replaced some of the recorded feature flag values",
  },
  {
    pattern: /_mob[0-9a-f]{8}(?=_|$)/g,
    describe: () =>
      "mobile variant (_mob): re-derived for a phone-sized viewport, with clicks retargeted where the mobile layout moved them",
  },
  {
    pattern: /_aux[0-9a-f]{8}(?=_|$)/g,
    describe: () =>
      "auxiliary-viewport copy (_aux): an unchanged copy of the recording, replayed with extra screenshots at the project's auxiliary viewport sizes",
  },
];

/**
 * What Meticulous changed in a session it derived from a user's recording,
 * read from the suffixes of its ID (in the order they were applied, since a
 * derived session can be derived again, e.g. `_p…_mut…_p…`) and the markers
 * in its data. Empty for an unmodified recording.
 */
export const describeSessionVariant = (
  sessionId: string,
  session: {
    context?: object;
    pollyHAR?: {
      pollyHAR?: Record<
        string,
        { log?: { entries?: Array<{ _meticulousNetworkPatched?: string }> } }
      >;
    };
  },
): string[] => {
  const lines = SUFFIX_DESCRIPTIONS.flatMap(({ pattern, describe }) =>
    [...sessionId.matchAll(pattern)].map((match) => ({
      index: match.index,
      line: `  - ${describe(match)}`,
    })),
  )
    .sort((a, b) => a.index - b.index)
    .map(({ line }) => line);
  if (
    session.context != null &&
    (session.context as Record<string, unknown>)[MUTATION_MARKER_KEY] === true
  ) {
    lines.push(
      "  - its recorded feature flags may not match what the app gets in this copy: the change can make the app behave as if flags were different",
    );
  }
  const patchedResponses = Object.values(session.pollyHAR?.pollyHAR ?? {})
    .flatMap((recording) => recording?.log?.entries ?? [])
    .filter((entry) => entry._meticulousNetworkPatched != null).length;
  if (patchedResponses > 0) {
    lines.push(
      `  - ${patchedResponses} recorded responses were patched or generated by Meticulous (patched= in session-requests/)`,
    );
  }
  return lines.length > 0
    ? [
        "Modified by Meticulous: this is not the user's original recording.",
        ...lines,
        "",
      ]
    : [];
};
